-- 0080 · Ordernummer (Nav 2.0, 2026-10-14)
--
-- =============================================================================
-- VARFÖR
--
-- Nav 2.0 talar om en order med ett nummer: "#12" i listan, i kundkortet, i
-- historiken och i kortkommandona. Navet har aldrig haft något — en order är ett
-- uuid, och det enda nummer som fanns var Inkios (O-…), som bara finns för de
-- order som skrivits dit. Utan en kolumn hade utkastet fått hitta på numret, och
-- ett påhittat nummer ändras så fort en order raderas.
--
-- Numret är bara en etikett. Ingenting räknar på det, ingenting söker på det
-- utom människor, och det säger inget om kunden (K27).
-- =============================================================================
--
-- =============================================================================
-- ADDITIV, OCH MAIN RÖRS INTE
--
-- Mains kod listar sina kolumner och skriver aldrig `order_number`. En ny order
-- från main får därför nästa nummer av databasen själv. Befintliga order numreras
-- i den ordning de lades upp (`created_at`, sedan `id` för samma tidpunkt), så
-- att den äldsta är #1.
--
-- `sales_order_stegbyte` rör inte kolumnen, och CRM- och leveranstriggrarna
-- lyssnar bara på `approved_at` och `status`. Uppdateringen nedan går alltså
-- igenom även på godkända och makulerade order, utan att något annat händer.
-- =============================================================================

alter table public.sales_order add column order_number bigint;

with numrerat as (
  select id, row_number() over (order by created_at, id) as nr
  from public.sales_order
)
update public.sales_order s
   set order_number = numrerat.nr
  from numrerat
 where numrerat.id = s.id;

alter table public.sales_order alter column order_number set not null;
alter table public.sales_order alter column order_number add generated by default as identity;

-- Sekvensen börjar efter det högsta numret, så att nästa order inte krockar.
select setval(
  pg_get_serial_sequence('public.sales_order', 'order_number'),
  coalesce((select max(order_number) from public.sales_order), 0) + 1,
  false
);

create unique index sales_order_order_number_key on public.sales_order (order_number);

comment on column public.sales_order.order_number is
  'Ordernumret i Nav 2.0 (#12). En etikett: ingenting räknar på det. Sätts av databasen.';
